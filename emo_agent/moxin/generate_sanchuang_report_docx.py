from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Pt


def set_default_font(doc: Document) -> None:
    style = doc.styles["Normal"]
    style.font.name = "微软雅黑"
    style._element.rPr.rFonts.set(qn("w:eastAsia"), "微软雅黑")
    style.font.size = Pt(11)


def add_title(doc: Document, text: str) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    run.bold = True
    run.font.size = Pt(22)
    run.font.name = "微软雅黑"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "微软雅黑")


def add_subtitle(doc: Document, text: str) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    run.font.size = Pt(12)
    run.font.name = "微软雅黑"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "微软雅黑")


def add_fill_item(doc: Document, title: str, hint: str, sample: str) -> None:
    doc.add_paragraph(f"【{title}】", style="List Bullet")
    doc.add_paragraph(f"填写提示：{hint}")
    doc.add_paragraph(f"示例文案：{sample}")


def add_chapter(doc: Document, chapter_title: str, items: list[tuple[str, str, str]]) -> None:
    doc.add_heading(chapter_title, level=1)
    for t, h, s in items:
        add_fill_item(doc, t, h, s)
    doc.add_paragraph("")


